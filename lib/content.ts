// 받침에 따라 '이란/란'을 붙입니다.
export const withIran = (word: string) => {
  const code = word.charCodeAt(word.length - 1) - 0xac00
  const hasFinal = code >= 0 && code <= 11171 && code % 28 !== 0
  return `${word}${hasFinal ? '이란' : '란'}`
}

